export function triggerById(id) {
  return TRIGGERS.find((t) => t.id === id);
}

export function dailyMessage(st, now) {
  const day = Math.floor(now / 864e5) + (st.shuf || 0);
  const i = ((day % MESSAGES.length) + MESSAGES.length) % MESSAGES.length;
  return MESSAGES[i];
}
